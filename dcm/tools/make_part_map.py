#!/usr/bin/env python3
"""Generate lib/part_map.csv: refdes -> PDF page, symbol, value, package.

Sources:
  refdes   reference/ipc356_pads.json
  value    schematic value from ROOT.DSN in source/gate_drive_power_dcm_fb_v3_ee10.pdsprj
  sheet    SHEET1 below: there is no PDF print of the DCM project (only the .pdsprj and the CADCAM
           zip), so the pages follow the asym board's PDF (the DCM board is the asym board with
           another toroid driver): the parts of page 1 there, everything else on page 2
  lib_id   SYMBOL_BY_VALUE (schematic value -> lib/gate_drive.kicad_sym symbol)
  package  PACKAGE_BY_REFDES_PREFIX / IPC pad pattern (the ROOT.LYT layout records of this
           Proteus 8.12 SP0 save are not in the format p2k.pdsprj.lyt_parts reads; the package
           names seen in its strings are CAPC1608X87 / 0603 / 1206 / RESC3216X65 / SOD2514X100)

  tools/make_part_map.py           write lib/part_map.csv
  tools/make_part_map.py --check   fail if lib/part_map.csv is not up to date
"""
import csv
import io
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "p2k"))  # proteus2kicad
from p2k import board, pdsprj  # noqa: E402

PRJ = board.path("source", "gate_drive_power_dcm_fb_v3_ee10.pdsprj")
# Page 1 of the asym PDF (gate drivers + J9); the supply parts (page 2 there) and the new DCM
# primary switch (Q1, R7, R11, R13, R14, D9, C9) are on page 2.
SHEET1 = frozenset("C5 C6 DRV1 DRV2 J9 R1 R2 R3 R4 R5 R6 R8 R12".split())
OUT = board.path("lib", "part_map.csv")
LIB = board.config().PROJECT


def symbol(ref, value):
    if ref.startswith("R"):
        return "R"
    if ref.startswith("C"):
        return "C"
    return {"ZLLS400TA": "D_Schottky", "MMSZ5228BS-7-F": "D_Zener", "SI8271": "SI8271",
            "MMBT3904": "Q_NPN", "PIN": "PIN", "HB GT CONNECTOR": "HB_GT_CONNECTOR"}[value]


def package(ref, pads):
    """Package from the IPC pad pattern (pad size and pad-centre span of 2-pad parts)."""
    if ref.startswith("DRV"):
        return "SOIC-8"
    if ref.startswith("Q"):
        return "SOT-23"
    if ref.startswith("J"):
        return "2x24 1.27 mm (pins 15-48)" if len(pads) > 1 else "wire pad 0.762 drill"
    if ref.startswith("D"):
        return "SOD-323"
    (a, b) = pads
    span = round(((a["x_mm"] - b["x_mm"]) ** 2 + (a["y_mm"] - b["y_mm"]) ** 2) ** 0.5, 2)
    return {1.6: "0603", 1.73: "0603", 2.9: "1206", 3.15: "1206"}[span]


FIELDS = ["refdes", "sheet", "lib_id", "value", "package"]


def build():
    ipc = json.load(open(board.path("reference", "ipc356_pads.json")))
    pads = {}
    for p in ipc["pads"]:
        if p["kind"] == "pad":
            pads.setdefault(p["refdes"], []).append(p)
    refs = set(pads)
    values = pdsprj.dsn_values(PRJ, refs)
    errors, rows = [], []
    for ref in sorted(refs):
        rows.append({"refdes": ref, "sheet": 1 if ref in SHEET1 else 2, "lib_id": f"{LIB}:{symbol(ref, values[ref])}",
                     "value": values[ref], "package": package(ref, pads[ref])})
    if errors:
        sys.exit("make_part_map:\n  " + "\n  ".join(errors))
    nat = lambda s: [(0, int(t), "") if t.isdigit() else (1, 0, t) for t in re.findall(r"\d+|\D+", s)]
    rows.sort(key=lambda r: (r["sheet"], nat(r["refdes"])))
    buf = io.StringIO()
    buf.write("# Generated by tools/make_part_map.py - do not edit. sheet = Proteus page (no PDF:"
              " as the asym board); value = schematic value (ROOT.DSN); package from the IPC pad pattern\n")
    w = csv.DictWriter(buf, fieldnames=FIELDS, lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue(), rows


def main():
    text, rows = build()
    rel = os.path.relpath(OUT, board.root())
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            print(f"make_part_map: {rel} is out of date, run tools/make_part_map.py")
            return 1
        print(f"make_part_map: {rel} up to date ({len(rows)} parts)")
        return 0
    open(OUT, "w").write(text)
    print(f"wrote {rel}: {len(rows)} parts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
